//! SHA-256 and HMAC-SHA-256, as published in FIPS 180-4 and RFC 2104.
//! Used to prove knowledge of a key without sending it (hive.rs). This is
//! not encryption, and nothing here keeps data secret.
//!
//! Written here because the kernel takes no outside crates; the tests check
//! it against the published values.

